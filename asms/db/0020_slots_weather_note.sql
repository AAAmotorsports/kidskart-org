-- =========================================================================
-- 0020_slots_weather_note.sql
-- -------------------------------------------------------------------------
-- 各スロット (開催枠) にその日の天候メモを記録できるカラムを追加。
--
-- 用途:
-- - 「7 月最終週は雨で午前だけ実施だった」など後で振り返るため
-- - 前年同月の天候傾向を確認して、来年の枠設計に活かす
-- - 顧客カルテで「〇〇君は前回雨天だったので今日はドライで初」等
--   走行環境の記録として
--
-- 自由記述 TEXT で運用。予約はまだ絵文字＋短文でスタッフが手打ち想定:
--   例: "☀️ 晴れ", "🌧 小雨、後半晴れ", "☁️ 曇り"
-- =========================================================================

alter table slots
  add column if not exists weather_note text;

comment on column slots.weather_note is
  '当日の天候メモ (絵文字＋短文推奨。例: "☀️ 晴れ 30℃", "🌧 小雨後半晴れ")';
