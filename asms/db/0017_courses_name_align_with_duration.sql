-- =========================================================================
-- 0017_courses_name_align_with_duration.sql
-- -------------------------------------------------------------------------
-- コース名と実際の走行時間の不一致を解消。
-- Reserva 時代の名前をそのまま踏襲していたが、実際の走行時間 (duration_min)
-- と乖離があり、当日「60 分と書いてあったのに 50 分だった」等のクレームの
-- 種になる。名前を実時間に合わせる。
--
-- 併せて description にヒート数を明記して分かりやすく。
--
--   repeat_60: 名前「リピート練習 60分」→「リピート練習 (50分)」
--              説明「4 ヒート走行」
--   repeat_30: 名前「リピート練習 30分」→「リピート練習 (25分)」
--              説明「2 ヒート走行」
--
-- 既存の予約は reservations 側で name_snapshot を持たない (courses に
-- 直接 join する) が、slot と course が別テーブルなので予約データ整合性
-- への影響なし。表示だけが更新される。
-- =========================================================================

begin;

update courses
   set name = 'リピート練習 (50分)',
       description = '4 ヒート走行'
 where code = 'repeat_60';

update courses
   set name = 'リピート練習 (25分)',
       description = '2 ヒート走行'
 where code = 'repeat_30';

commit;
